-- Run this in Supabase SQL Editor for the Sociothon app.
-- The app signs users in anonymously, so enable Anonymous Sign-Ins in
-- Authentication > Providers > Anonymous before using the app.

create table if not exists public.case_reports (
  id bigint generated by default as identity primary key,
  external_id text not null unique,
  patient_name text not null,
  age integer,
  gender text,
  disease text,
  water_source text,
  severity text,
  notes text,
  village_key text,
  village_name text,
  reported_at timestamptz not null default now()
);

create table if not exists public.municipal_alerts (
  id bigint generated by default as identity primary key,
  title text not null,
  detail text,
  author text,
  created_at timestamptz not null default now()
);

create table if not exists public.alert_emails (
  id bigint generated by default as identity primary key,
  email text not null unique,
  full_name text,
  role text not null default 'citizen',
  house_key text default 'house-1',
  house_name text default 'House No. 1',
  notify_fire boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.fire_alerts (
  id bigint generated by default as identity primary key,
  alert_id text not null unique,
  origin_label text not null,
  house_key text,
  cause text,
  notified_houses jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.case_reports enable row level security;
alter table public.municipal_alerts enable row level security;
alter table public.alert_emails enable row level security;
alter table public.fire_alerts enable row level security;

drop policy if exists "Anonymous app users can read case reports" on public.case_reports;
create policy "Anonymous app users can read case reports"
  on public.case_reports for select to authenticated using (true);
drop policy if exists "Anonymous app users can add case reports" on public.case_reports;
create policy "Anonymous app users can add case reports"
  on public.case_reports for insert to authenticated with check (true);
drop policy if exists "Anonymous app users can update case reports" on public.case_reports;
create policy "Anonymous app users can update case reports"
  on public.case_reports for update to authenticated using (true) with check (true);

drop policy if exists "Anonymous app users can read municipal alerts" on public.municipal_alerts;
create policy "Anonymous app users can read municipal alerts"
  on public.municipal_alerts for select to authenticated using (true);
drop policy if exists "Anonymous app users can add municipal alerts" on public.municipal_alerts;
create policy "Anonymous app users can add municipal alerts"
  on public.municipal_alerts for insert to authenticated with check (true);

-- Keep the contact registry private to trusted server-side code. Remove any
-- previous client policies and grants; intentionally add none for this table.
drop policy if exists "Anonymous app users can read alert emails" on public.alert_emails;
drop policy if exists "Anonymous app users can add alert emails" on public.alert_emails;
drop policy if exists "Anonymous app users can update alert emails" on public.alert_emails;

drop policy if exists "Anonymous app users can read fire alerts" on public.fire_alerts;
create policy "Anonymous app users can read fire alerts"
  on public.fire_alerts for select to authenticated using (true);
drop policy if exists "Anonymous app users can add fire alerts" on public.fire_alerts;
create policy "Anonymous app users can add fire alerts"
  on public.fire_alerts for insert to authenticated with check (true);

grant select, insert, update on public.case_reports to authenticated;
grant select, insert on public.municipal_alerts to authenticated;
grant select, insert on public.fire_alerts to authenticated;
grant usage, select on sequence public.case_reports_id_seq to authenticated;
grant usage, select on sequence public.municipal_alerts_id_seq to authenticated;
grant usage, select on sequence public.fire_alerts_id_seq to authenticated;
revoke all on public.alert_emails from public, anon, authenticated;
grant all on public.alert_emails to service_role;
grant usage, select on sequence public.alert_emails_id_seq to service_role;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'case_reports'
  ) then
    alter publication supabase_realtime add table public.case_reports;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'municipal_alerts'
  ) then
    alter publication supabase_realtime add table public.municipal_alerts;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'fire_alerts'
  ) then
    alter publication supabase_realtime add table public.fire_alerts;
  end if;
end $$;

